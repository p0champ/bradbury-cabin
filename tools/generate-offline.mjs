// Reproducible complete static inventory. This is separate from the strict
// literary-source checks, which still run unchanged in the release gate.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { STATIC_ASSETS } from '../static-assets.mjs';
export const staticHash = (bytes, text) => createHash('sha256').update(text ? bytes.toString('utf8').replace(/\r\n/g, '\n') : bytes).digest('hex');
export async function makeOfflineEdition(read = name => readFile(new URL('../' + name, import.meta.url))) {
  const assets = [];
  for (const path of [...STATIC_ASSETS].filter(p => p !== 'offline-manifest.js').sort()) {
    const text = /\.(?:html|js|css|md|txt)$/.test(path);
    assets.push({ path, sha256: staticHash(await read(path), text), text });
  }
  return { digest: staticHash(Buffer.from(JSON.stringify(assets)), false), assets };
}
export const manifestSource = edition => `// Generated by tools/generate-offline.mjs; do not edit.\nself.CABIN_OFFLINE = ${JSON.stringify(edition, null, 2)};\n`;
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const expected = manifestSource(await makeOfflineEdition());
  const file = new URL('../offline-manifest.js', import.meta.url);
  if (process.argv.includes('--check')) {
    if ((await readFile(file, 'utf8')).replace(/\r\n/g, '\n') !== expected) throw Error('Offline edition is stale; regenerate it before checking.');
    console.log('Complete offline edition matches every public file.');
  } else await writeFile(file, expected);
}
